BLOQUE 1: DEFINICIÓN DE TABLAS (DDL - 10 TABLAS FINANCIERAS + 1 PUENTE)

-- 1. TABLA: proveedor (Laboratorios y distribuidores mayoristas de medicamentos)
CREATE TABLE proveedor (
    proveedor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL,
    ruc VARCHAR2(11) NOT NULL CONSTRAINT uq_proveedor_ruc UNIQUE,
    telefono VARCHAR2(20),
    direccion VARCHAR2(200),
    email VARCHAR2(100),
    estado NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. TABLA PUENTE: medicamento_ref (Sincronización distribuida con PostgreSQL)
-- Permite validar integridad referencial en órdenes de compra sin violar el desacoplamiento
CREATE TABLE medicamento_ref (
    medicamento_id NUMBER PRIMARY KEY,
    codigo VARCHAR2(50) NOT NULL CONSTRAINT uq_medref_codigo UNIQUE,
    nombre VARCHAR2(200) NOT NULL,
    precio_compra NUMBER(10,2) NOT NULL,
    estado NUMBER(1) DEFAULT 1 NOT NULL
);

-- 3. TABLA: compra (Órdenes de compra mayoristas consolidadas para la red)
CREATE TABLE compra (
    compra_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id NUMBER NOT NULL,
    farmacia_id NUMBER NOT NULL,
    proveedor_id NUMBER NOT NULL REFERENCES proveedor(proveedor_id),
    fecha_compra DATE DEFAULT SYSDATE NOT NULL,
    fecha_recepcion DATE,
    total NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    estado VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL 
        CONSTRAINT chk_compra_estado CHECK (estado IN ('PENDIENTE', 'RECIBIDA', 'PAGADA', 'ANULADA')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 4. TABLA: detalle_compra (Ítems de medicamentos adquiridos por orden de compra)
CREATE TABLE detalle_compra (
    detalle_compra_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id NUMBER NOT NULL REFERENCES compra(compra_id) ON DELETE CASCADE,
    medicamento_id NUMBER NOT NULL REFERENCES medicamento_ref(medicamento_id),
    cantidad NUMBER NOT NULL CONSTRAINT chk_detcompra_cant CHECK (cantidad > 0),
    precio_unitario NUMBER(10,2) NOT NULL CONSTRAINT chk_detcompra_pu CHECK (precio_unitario > 0),
    subtotal NUMBER(10,2) NOT NULL
);

-- 5. TABLA: pagos_proveedor (Registro de abonos bancarios para liquidar órdenes)
CREATE TABLE pagos_proveedor (
    pago_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id NUMBER NOT NULL REFERENCES proveedor(proveedor_id),
    compra_id NUMBER REFERENCES compra(compra_id),
    monto_pago NUMBER(10,2) NOT NULL CONSTRAINT chk_pago_monto CHECK (monto_pago > 0),
    fecha_pago DATE DEFAULT SYSDATE NOT NULL,
    metodo_pago VARCHAR2(20) CONSTRAINT chk_pago_metodo CHECK (metodo_pago IN ('TRANSFERENCIA', 'CHEQUE', 'EFECTIVO')),
    estado VARCHAR2(20) DEFAULT 'PAGADO' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 6. TABLA: documentos_tributarios (Facturas y boletas electrónicas SUNAT)
CREATE TABLE documentos_tributarios (
    documento_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id NUMBER REFERENCES compra(compra_id),
    proveedor_id NUMBER NOT NULL REFERENCES proveedor(proveedor_id),
    tipo_documento VARCHAR2(20) CONSTRAINT chk_doc_tipo CHECK (tipo_documento IN ('FACTURA', 'BOLETA', 'GUIA')),
    serie VARCHAR2(10),
    numero VARCHAR2(20),
    ruc VARCHAR2(11),
    igv NUMBER(10,2),
    fecha_emision DATE DEFAULT SYSDATE NOT NULL,
    monto_total NUMBER(10,2) NOT NULL,
    estado VARCHAR2(20) DEFAULT 'EMITIDO' NOT NULL
);

-- 7. TABLA: impuestos (Tasas impositivas vigentes: IGV 18%, ISC, Renta)
CREATE TABLE impuestos (
    impuesto_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    porcentaje NUMBER(5,2) NOT NULL,
    descripcion VARCHAR2(200),
    estado NUMBER(1) DEFAULT 1 NOT NULL
);

-- 8. TABLA: centro_costo (Unidades administrativas y operativas de imputación)
CREATE TABLE centro_costo (
    centro_costo_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(20) NOT NULL CONSTRAINT uq_cc_codigo UNIQUE,
    nombre VARCHAR2(100) NOT NULL,
    estado NUMBER(1) DEFAULT 1 NOT NULL
);

-- 9. TABLA: cuenta (Plan contable general empresarial adaptado al sector farmacéutico)
CREATE TABLE cuenta (
    cuenta_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(20) NOT NULL CONSTRAINT uq_cuenta_codigo UNIQUE,
    nombre VARCHAR2(150) NOT NULL,
    tipo VARCHAR2(50) NOT NULL,
    nivel NUMBER DEFAULT 1 NOT NULL,
    estado NUMBER(1) DEFAULT 1 NOT NULL
);

-- 10. TABLA: asiento_contable (Libro diario contable para transacciones financieras)
CREATE TABLE asiento_contable (
    asiento_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE DEFAULT SYSDATE NOT NULL,
    descripcion VARCHAR2(200),
    total_debe NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    total_haber NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- 11. TABLA: detalle_asiento (Partida doble: débitos y créditos por cada cuenta)
CREATE TABLE detalle_asiento (
    detalle_asiento_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiento_id NUMBER NOT NULL REFERENCES asiento_contable(asiento_id) ON DELETE CASCADE,
    cuenta_id NUMBER NOT NULL REFERENCES cuenta(cuenta_id),
    centro_costo_id NUMBER REFERENCES centro_costo(centro_costo_id),
    total_debe NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    total_haber NUMBER(10,2) DEFAULT 0.00 NOT NULL
);

