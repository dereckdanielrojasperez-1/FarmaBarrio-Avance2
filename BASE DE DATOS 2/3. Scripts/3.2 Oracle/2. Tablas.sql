-- Tablas del modelo financiero y compras B2B en Oracle XE (10 tablas + puente)
BLOQUE 0: LIMPIEZA INICIAL SEGURA (DROP TABLE CON CASCADE CONSTRAINTS PURGE)
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN (
            'DETALLE_ASIENTO', 'ASIENTO_CONTABLE', 'DOCUMENTOS_TRIBUTARIOS',
            'PAGOS_PROVEEDOR', 'DETALLE_COMPRA', 'COMPRA', 'MEDICAMENTO_REF',
            'PROVEEDOR', 'IMPUESTOS', 'CENTRO_COSTO', 'CUENTA'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
        DBMS_OUTPUT.PUT_LINE('Tabla eliminada: ' || t.table_name);
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Aviso en limpieza: ' || SQLERRM);
END;
/

